  function cancelledError() {
    return new SG.errors.GenerationError('budget.cancelled', {});
  }

  /**
   * Calls `run` after the browser has painted: two animation frames (the second one fires after a paint),
   * then a zero timeout. A timer covers a hidden tab, which paints nothing. Returns a function that cancels.
   */
  function waitForPaint(run) {
    let frame1 = null;
    let frame2 = null;
    let timer = null;
    let fallback = null;
    let done = false;
    function clearAll() {
      if (frame1 !== null) cancelFrame(frame1);
      if (frame2 !== null) cancelFrame(frame2);
      if (timer !== null) root.clearTimeout(timer);
      if (fallback !== null) root.clearTimeout(fallback);
      frame1 = frame2 = timer = fallback = null;
    }
    function fire() {
      if (done) return;
      done = true;
      clearAll();
      run();
    }
    frame1 = requestFrame(function () {
      frame1 = null;
      frame2 = requestFrame(function () {
        frame2 = null;
        timer = root.setTimeout(fire, 0);
      });
    });
    fallback = root.setTimeout(fire, PAINT_FALLBACK_MS);
    return function cancelWait() {
      done = true;
      clearAll();
    };
  }

  /**
   * The generation client of the main thread, with the interface of the Web Worker client
   * (`SG.workerClient`, design.md 9.3): `generate(config, onEvent) -> Promise<PuzzleResult>`, `cancel()`,
   * `mode`. It yields to the browser so that the busy state is painted, then runs `SG.pipeline.run`
   * synchronously, collects the events in a buffer and hands them to `onEvent` when the run is over.
   * LIMIT: see the file header (a cancel is only possible before the run starts).
   */
  const directClient = (function () {
    let token = 0;
    let abort = null;

    function deliver(events, onEvent) {
      if (typeof onEvent !== 'function') return;
      for (let i = 0; i < events.length; i++) safely(onEvent, events[i]);
    }

    function cancel() {
      token++;
      if (abort !== null) {
        const stop = abort;
        abort = null;
        stop();
      }
    }

    function generate(config, onEvent) {
      cancel();
      const mine = token;
      return new Promise(function (resolve, reject) {
        function run() {
          if (mine !== token) return;
          abort = null;
          const events = [];
          let result;
          try {
            const budget = SG.budget.create({ ms: MAIN_THREAD_LIMIT_MS });
            result = SG.pipeline.run(config, function (event) { events.push(event); }, budget);
          } catch (err) {
            deliver(events, onEvent);
            reject(err);
            return;
          }
          deliver(events, onEvent);
          resolve(result);
        }
        const stopWaiting = waitForPaint(run);
        abort = function () {
          stopWaiting();
          reject(cancelledError());
        };
      });
    }

    return { generate: generate, cancel: cancel, mode: 'main' };
  })();

