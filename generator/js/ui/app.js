/**
 * Application wiring (task T-4.7; design.md sections 3.2, 3.3, 9.3, 10.1 and 14.2): `SG.app`. It owns the
 * page: reads the URL and the stored preferences, builds the board, the controls, the replay player, the
 * steps panel and the result panel, runs a generation, and replays how the puzzle was made (from its dig
 * log, `PuzzleResult.digLog`). The explanation of the steps lives in the Help dialog (`SG.help`, tab "How
 * it works"). Every
 * other UI module is a self-contained building block; this file only connects them. It starts by itself when
 * the DOM is ready (nothing happens without a DOM or without the mount points of index.html, so the file also
 * loads in Node and in tests.html).
 *
 * ---------------------------------------------------------------------------------------------------------
 * PUBLIC API (`SG.app`) - later modules (export, a11y, theme, help, cache) only use this
 * ---------------------------------------------------------------------------------------------------------
 *   getStore()      -> the shared `SG.store` instance (valid from the start).
 *   getBoard()      -> the CURRENT `SG.boardView` view (null before start). The same view object lives for
 *                      the whole session; a new puzzle is installed with `board.setModel`. Do not keep a
 *                      model of your own: read `getResult()`.
 *   getPlayer()     -> the replay player (null before start).
 *   getStepView()   -> the steps panel (null before start).
 *   getExplainContext() -> `{ stepId, lineLabel, metrics, position, length }` or null. What the Help dialog
 *                      explains as the current step: `stepId` is the pipeline step ('fullGrid',
 *                      'extraStructure' or 'dig') of the replay step on show, `lineLabel` the pseudocode line
 *                      it corresponds to, `metrics` the dig counters (null outside the dig). Null while
 *                      there is no replay.
 *   getResult()     -> `{ result, trace }` of the last successful generation (a `PuzzleResult` and its event
 *                      trace), or null while nothing is shown (before the first run, during a run, after an
 *                      error or a cancel).
 *   generate(overrides?) -> Promise<?PuzzleResult>. Starts a generation from the store state. `overrides` is
 *                      a partial store state (for example `{ seed: '42', difficulty: 'hard' }`) that is
 *                      first written to the store, so the form shows what is being generated. A run that is
 *                      replaced by a newer one, cancelled, or that fails resolves with null (failures are
 *                      reported through the 'generate:error' event and a toast, never as a rejection).
 *   regenerate()    -> Promise<?PuzzleResult>. A new random seed is written to the store, then `generate()`.
 *   generate(overrides?, options?): `options.random` (true for `regenerate()`) tells the client that the seed
 *                      in the config was just drawn at random, so any random puzzle of the same configuration
 *                      will do (the cache serves a pre-generated one); it reaches the client as the third
 *                      argument of `client.generate(config, onEvent, { random })`.
 *   getClient()     -> the generation client in use (null before start).
 *   setClient(next) -> Replaces the generation client (a wrapper with the same interface; null restores the
 *                      default). Call it between runs.
 *   attachTrace(trace, digLog?) -> boolean. Gives the puzzle on screen what arrived after it was shown (a
 *                      result served from the cache has no dig log and `getResult().trace === []`): the
 *                      trace, and the dig log when the result had none. The player then loads the replay at
 *                      its END (the finished puzzle), so the steps panel and the replay
 *                      controls work as after a normal run. False when nothing is shown, a run is in progress
 *                      or there is still no dig log. Fires 'trace' with `{ result, trace }`.
 *   cancel()        -> boolean. Stops the running generation (see the limit of the main-thread client below).
 *   showResult(result, { trace }) -> boolean. Shows a `PuzzleResult` that was not generated by the
 *                      pipeline run of this page: the board shows its clues, the result panel what it can,
 *                      the replay is built when the result has a `digLog`; `trace` (default: none) is kept as
 *                      its events. A running generation is
 *                      replaced. It fires 'result' with `{ result, trace, imported: true }` (and not
 *                      'generate:end'; nothing was generated).
 *   toast(kind, key, args?) -> { close() }. `kind`: 'success' | 'warning' | 'danger' | 'info'; `key` is a
 *                      translation key; the toast closes by itself and has a close button.
 *   openModal({ titleKey, titleArgs, body, footer, wide, onClose }) -> { el, panel, body, footer, close(),
 *                      setTitle(key, args) }. A `<dialog class="modal">` in `#modal-root`: `body` / `footer`
 *                      are a Node or `function (container)` that fills the given container (and may return a
 *                      Node). Esc, the backdrop and the close button close it, focus returns to where it was,
 *                      `body.is-modal-open` is set while one is open. `onClose()` runs once.
 *   announce(text)  -> writes `text` to the polite live region `#a11y-live` (a screen reader says it).
 *   on(name, fn)    -> off(). Subscribes to an app event; `emit(name, payload)` fires one (modules may emit
 *                      their own events). Events of the app:
 *       'generate:start'     { config }
 *       'generate:progress'  one `GenerationEvent` (worker mode: while the run goes on; main thread: all at
 *                            the end)
 *       'generate:end'       the `PuzzleResult`
 *       'generate:error'     the error (a `GenerationError` or any `Error`)
 *       'generate:cancel'    null
 *       'result'             `{ result, trace }`, after the board shows the new puzzle
 *       'trace'              `{ result, trace }`, after `attachTrace` gave the puzzle its replay
 *       'position'           `{ position, length, step, direction }` after every move of the replay
 *                            (`step` is a step of `SG.player.buildSteps`, null at position 0)
 *       'locale'             { locale }
 *       'theme'              { theme }
 *       'settings'           { state, keys, meta } for every change of the store
 *       'action'             { id }: a click on `#btn-export` ('export': Print), `#btn-export-code`
 *                            ('exportCode'), `#btn-play-online` ('play'), `#btn-settings` ('settings'),
 *                            `#btn-help` ('help') or `#btn-explain` ('help' with `tab: 'generation'`);
 *                            when nobody listens the user gets an "unavailable" toast
 *   start() / destroy()   idempotent; `start` runs automatically on DOMContentLoaded.
 *
 * OPTIONAL MODULES: at the end of start-up the app calls `init(SG.app)` on each of `SG.exportUi`,
 * `SG.a11y`, `SG.theme`, `SG.help`, `SG.cache`, `SG.history` that exists, in this order, each in
 * its own try/catch (a module that throws is logged and skipped, the app goes on). `#btn-export`,
 * `#btn-export-code` and `#btn-play-online` (all in the top right corner of the main panel) are enabled
 * once a puzzle is shown AND somebody listens to 'action'.
 *
 * Generation client: `const client = SG.workerClient || directClient`. A client is
 * `{ generate(config, onEvent) -> Promise<PuzzleResult>, cancel(), mode: 'worker' | 'main' }`. The internal
 * `directClient` runs `SG.pipeline.run` on the main thread (mode 'main'). LIMIT: the pipeline is synchronous
 * and cannot yield, so the page cannot respond while it runs and `cancel()` (or a newer `generate`) only
 * takes effect while the client is still waiting to paint the busy state; a run that has started always
 * finishes (or hits its time budget) and its result is then dropped by the session token of the app.
 * Moving the run into a Web Worker (SG.workerClient) removes the limit without a change here. A client that
 * detects Worker support in the background may offer `ready() -> Promise`.
 *
 * Replay contract: the board is built from the FINAL model of the result and shows the finished puzzle at
 * once; nothing plays by itself. The player builds the replay steps from `result.digLog` (not from the
 * trace) and its `onPosition` is the one place that drives the steps panel.
 */
