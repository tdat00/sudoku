  function listenerCount(name) {
    return listeners[name] ? listeners[name].length : 0;
  }

  /**
   * Subscribes to an event of the app (see the file header for the list).
   * @param {string} name
   * @param {function(*, string): void} fn  Called with `(payload, name)`; a throwing listener is logged.
   * @returns {function(): void} Removes the listener.
   */
  function on(name, fn) {
    if (typeof name !== 'string' || typeof fn !== 'function') {
      throw new TypeError('SG.app.on needs an event name and a function');
    }
    (listeners[name] = listeners[name] || []).push(fn);
    if (started && name === 'action') updateButtons();
    return function off() {
      if (!listeners[name]) return;
      listeners[name] = listeners[name].filter(function (other) { return other !== fn; });
      if (started && name === 'action') updateButtons();
    };
  }

  /**
   * Fires an event.
   * @param {string} name
   * @param {*} [payload]
   */
  function emit(name, payload) {
    (listeners[name] || []).slice().forEach(function (fn) {
      try {
        fn(payload, name);
      } catch (err) {
        logError(err);
      }
    });
  }

  // ---------------------------------------------------------------------------------------------
  // Live region, toasts, modals
