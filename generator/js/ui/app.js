  // Small helpers
  // ---------------------------------------------------------------------------------------------

  function t(key, args) {
    return SG.i18n.t(key, args);
  }

  function logError(err) {
    if (typeof console !== 'undefined' && typeof console.error === 'function') console.error(err);
  }

  function safely(fn, arg) {
    try {
      return fn(arg);
    } catch (err) {
      logError(err);
      return undefined;
    }
  }

  function byId(id) {
    return typeof document !== 'undefined' ? document.getElementById(id) : null;
  }

  /** Creates an element; attribute values of null / undefined / false are skipped, `true` gives ''. */
  function make(tag, attrs, children) {
    const node = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (name) {
      const value = attrs[name];
      if (value === null || value === undefined || value === false) return;
      if (name === 'class') node.className = value;
      else if (name === 'text') node.textContent = value;
      else node.setAttribute(name, value === true ? '' : String(value));
    });
    (children || []).forEach(function (child) { node.appendChild(child); });
    return node;
  }

  function icon(name) {
    const use = document.createElementNS(SVG_NS, 'use');
    use.setAttribute('href', '#ic-' + name);
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('class', 'icon');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    svg.appendChild(use);
    return svg;
  }

  function requestFrame(fn) {
    if (typeof root.requestAnimationFrame === 'function') return root.requestAnimationFrame(fn);
    return root.setTimeout(fn, 16);
  }

  function cancelFrame(id) {
    if (typeof root.cancelAnimationFrame === 'function') root.cancelAnimationFrame(id);
    else root.clearTimeout(id);
  }

  /**
   * The font-size setting as a value for `--sg-font-size-base`.
   * @param {string} size  'small' | 'normal' | 'large'.
   * @returns {string} '87.5%' | '100%' | '125%'; the normal size for anything else.
   */
  function fontSizeValue(size) {
    return Object.prototype.hasOwnProperty.call(FONT_SIZES, size) ? FONT_SIZES[size] : FONT_SIZES.normal;
  }

  /**
   * The `data-theme` attribute of a theme setting.
   * @param {string} theme  'auto' | 'light' | 'dark' | 'high-contrast'.
   * @returns {?string} The attribute value; null for 'auto' (no attribute: `prefers-color-scheme` rules).
   */
  function themeAttribute(theme) {
    return theme === 'light' || theme === 'dark' || theme === 'high-contrast' ? theme : null;
  }

