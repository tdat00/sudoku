'use strict';
// Scratch (MS14b, S-AV37): the cost of the Law of Leftovers finder on the populations this task owns, kept apart:
//   blank   the blank state of the five test layouts (constructed stress, MS14a's numbers re-measured on the final source);
//   seeded  the 60 seeded dug puzzles of the suite (5 layouts x orientation x seeds 1-6) at the position where the registry
//           reaches the technique (work and latency of that call);
//   real    the calls the logical solver makes on the real Jigsaw puzzles of the bundle-B sources: the 12 puzzles of discovery
//           batch 1 (jigsaw9 hard, seeds 1-12, regenerated by the same request the tool made, and checked against the source
//           the tool recorded) and the two existing real sources (jigsawHelpSource and puzzle 1 of the structured export): every
//           call along the canonical solve (observer records of SG.logicalSolver.solve), then the same positions replayed for the
//           latency of the call.
//   node s-av37.js <out.json>
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const SG = require('./load.js');
const J = SG.fixtures.jigsawModels;
const H = SG.techHelper;
const tech = SG.techniques.get('lawOfLeftovers');
const ROOT = path.resolve(__dirname, '..', '..', '..', '..', '..');
const LIMIT = SG.leftoverPatterns.LIMITS.work;
const BELOW = SG.techniques.list().filter((t) => t.order < tech.order &&
  (t.variantScope === null || t.variantScope.indexOf('jigsaw9') !== -1)).map((t) => t.id);

const nowMs = () => Number(process.hrtime.bigint()) / 1e6;
function stats(values) {
  if (values.length === 0) return null;
  const s = values.slice().sort((a, b) => a - b);
  const at = (p) => s[Math.max(0, Math.ceil(p * s.length) - 1)];
  const r3 = (x) => Math.round(x * 1000) / 1000;
  return { n: s.length, min: r3(s[0]), p50: r3(at(0.5)), p95: r3(at(0.95)), max: r3(s[s.length - 1]),
    mean: r3(s.reduce((a, b) => a + b, 0) / s.length) };
}
function timeCall(model, state, repeats) {
  const samples = [];
  let record = null;
  let found = null;
  for (let k = 0; k < repeats; k++) {
    const ctx = SG.techniques.createContext(model, { onPatternWork: (r) => { record = r; } });
    const t0 = nowMs();
    found = tech.find(model, state, ctx);
    samples.push(nowMs() - t0);
  }
  samples.sort((a, b) => a - b);
  return { ms: samples[Math.floor(samples.length / 2)], record, found };
}

const out = { tool: 's-av37.js', node: process.version, limit: LIMIT, engine: null, populations: {} };
out.engine = {
  'core/js/engine/tech-subset.js': crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, 'core/js/engine/tech-subset.js'))).digest('hex'),
  'generator/js/engine/difficulty.js': crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, 'generator/js/engine/difficulty.js'))).digest('hex')
};

// ---- blank: constructed stress
{
  const rows = [];
  ['staggered', 'wavy', 'mixed', 'crossed', 'boxes'].forEach((name) => {
    const model = J.build(J.parse(J.LAYOUTS[name]));
    const state = SG.model.initState(model);
    const t = timeCall(model, state, 5);
    const records = [];
    SG.leftoverPatterns.find(model, state, SG.techniques.createContext(model, { onPatternWork: (r) => records.push(r) }), { workLimit: 100000000 });
    rows.push({ layout: name, regions: J.LAYOUTS[name].join(' '), defaultWork: t.record.work, defaultCap: t.record.capHit,
      defaultMs: Math.round(t.ms * 1000) / 1000, fullWork: records[0].work });
  });
  out.populations.blank = { note: 'constructed: every candidate open, nothing placed; not real positions', rows };
}

// ---- seeded: dug puzzles at the registry position
{
  const rows = [];
  const works = [];
  const times = [];
  let capped = 0;
  let found = 0;
  ['staggered', 'wavy', 'mixed', 'ordered', 'crossed'].forEach((name) => {
    [false, true].forEach((transposed) => {
      let layout = J.parse(J.LAYOUTS[name]);
      if (transposed) layout = J.transpose(layout);
      const model = J.build(layout);
      for (let seed = 1; seed <= 6; seed++) {
        const rng = SG.testkit.rng.create(seed * 7919 + (transposed ? 1 : 0));
        const solution = J.solve(model, rng.fork('grid'));
        const dug = SG.testkit.dig(model, solution, rng.fork('dig'), { minClues: 0 });
        const state = H.stateAfter(model, dug.givens, BELOW);
        const t = timeCall(model, state, 5);
        works.push(t.record.work);
        times.push(t.ms);
        if (t.record.capHit !== null) capped++;
        if (t.found !== null) found++;
        rows.push({ layout: name + (transposed ? ' (transposed)' : ''), seed, clues: dug.clues, open: state.unsolvedCount,
          work: t.record.work, cap: t.record.capHit, found: t.found !== null });
      }
    });
  });
  out.populations.seeded = { note: 'seeded dug puzzles on test layouts, at the position after the registry techniques below it',
    positions: rows.length, found, capped, work: stats(works), ms: stats(times), rows };
}

// ---- real: the Jigsaw puzzles of bundle B
function parseExport(text) {
  const lines = text.trim().split(/\r?\n/);
  const header = lines[0];
  const rows = lines.slice(1, 10);
  const regions = /^regions:\s*(.*)$/.exec(lines[10])[1].split(/\s+/).join('');
  const givens = Int32Array.from(rows.join('').split('').map((c) => (c === '.' ? 0 : Number(c))));
  const cellRegion = regions.split('').map((c) => Number(c) - 1);
  return { header, givens, cellRegion, regions: lines[10].replace(/^regions:\s*/, '') };
}

function measureReal(label, model, givens, extra) {
  const records = [];
  const report = SG.logicalSolver.solve(model, givens, { collectSteps: true, onPatternWork: (r) => { if (r.id === 'lawOfLeftovers') records.push(r); } });
  // replay the steps to the positions where the solver called the finder (before every step of a technique at or after its order)
  const state = SG.model.initState(model);
  for (let c = 0; c < model.cellCount; c++) if (givens[c] !== 0) SG.constraints.assign(model, state, c, givens[c]);
  const times = [];
  const replayWork = [];
  report.steps.forEach((step) => {
    const order = SG.techniques.get(step.technique).order;
    if (order >= tech.order) {
      const t = timeCall(model, state, 5);
      times.push(t.ms);
      replayWork.push(t.record.work);
    }
    step.placements.forEach((p) => SG.constraints.assign(model, state, p[0], p[1]));
    step.eliminations.forEach((e) => SG.constraints.eliminate(model, state, e[0], e[1]));
    SG.constraints.propagate(model, state);
  });
  const sameWork = replayWork.length === records.length && replayWork.every((w, i) => w === records[i].work);
  const works = records.map((r) => r.work);
  return Object.assign({ label, status: report.status, clues: Array.from(givens).filter((g) => g !== 0).length,
    steps: report.steps.length, steps_lawOfLeftovers: report.steps.filter((s) => s.technique === 'lawOfLeftovers').length,
    calls: records.length, work: stats(works), maxWork: works.length ? Math.max(...works) : 0,
    capHits: records.filter((r) => r.capHit !== null).length, replayedCalls: replayWork.length, replayMatchesObserver: sameWork,
    ms: stats(times) }, extra);
}

{
  const rows = [];
  // regenerate the 12 requests of discovery batch 1 exactly as the tool's child makes them
  SG.i18n.setLocale('en');
  const recorded = JSON.parse(fs.readFileSync(path.join(ROOT, 'player/tests/artifacts/difficulty-v3/MS14b/sources.json'), 'utf8'))
    .sources.lawOfLeftovers[0];
  let checkedAgainstRecord = null;
  for (let seed = 1; seed <= 12; seed++) {
    const result = SG.pipeline.run({ variantId: 'jigsaw9', difficulty: 'hard', seed, trace: 'off', variantOptions: {} }, null,
      SG.budget.create({ ms: 120000 }));
    const text = SG.exportUi.buildExportText([{ result }]).trim();
    if (String(seed) === recorded.seed) checkedAgainstRecord = text === recorded.text;
    const parsed = parseExport(text);
    const model = J.build(parsed.cellRegion);
    const same = JSON.stringify(Array.from(result.model.layout.cellRegion)) === JSON.stringify(parsed.cellRegion) &&
      JSON.stringify(result.model.units) === JSON.stringify(model.units);
    rows.push(measureReal('discovery batch 1: jigsaw9 hard seed ' + seed, model, parsed.givens,
      { source: 'discovery batch 1', seed: String(seed), level: 'hard', regions: parsed.regions, modelEqualsPipeline: same,
        textSha256: crypto.createHash('sha256').update(text).digest('hex').slice(0, 16) }));
  }
  out.populations.realChecks = { winnerSeed: recorded.seed, regeneratedEqualsRecordedSource: checkedAgainstRecord };
  const existing = JSON.parse(fs.readFileSync(path.join(ROOT, 'player/tests/artifacts/difficulty-v3/MS14b/sources-existing.json'), 'utf8'))
    .sources.lawOfLeftovers;
  existing.forEach((src, i) => {
    const parsed = parseExport(src.text);
    rows.push(measureReal('existing source ' + (i + 1) + ': jigsaw9 ' + src.level + ' seed ' + src.seed, J.build(parsed.cellRegion), parsed.givens,
      { source: i === 0 ? 'jigsawHelpSource (MS03c)' : 'structured export puzzle 1 (player fixture)', seed: src.seed, level: src.level, regions: parsed.regions }));
  });
  const all = rows.filter((r) => r.calls > 0);
  const works = [];
  rows.forEach((r) => { if (r.work) works.push(r.maxWork); });
  out.populations.real = {
    note: 'every call of the finder along the canonical solve of real Jigsaw puzzles (observer records), latency replayed on the same positions',
    puzzles: rows.length, calls: rows.reduce((n, r) => n + r.calls, 0), capHits: rows.reduce((n, r) => n + r.capHits, 0),
    maxWork: Math.max(...rows.map((r) => r.maxWork)), puzzlesWithAStep: rows.filter((r) => r.steps_lawOfLeftovers > 0).length,
    stepsOfTheTechnique: rows.reduce((n, r) => n + r.steps_lawOfLeftovers, 0), allReplaysMatch: rows.every((r) => r.replayMatchesObserver),
    allSolved: rows.every((r) => r.status === 'solved'), rows, withCalls: all.length
  };
}

fs.writeFileSync(path.resolve(process.argv[2] || 's-av37.json'), JSON.stringify(out, null, 2).replace(/\n/g, '\r\n') + '\r\n', 'utf8');
